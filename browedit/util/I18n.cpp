	void setLanguage(const std::string& lang)
	{
		g_currentLang = lang;
		if (lang == "zh")
		{
			ensureZhLoaded();
			g_table = g_zhTable;
		}
		else
		{
			g_table.clear();
		}
	}

	const std::string& getLanguage() { return g_currentLang; }

	const char* tr(const char* key)
	{
		if (g_currentLang == "en" || g_table.empty() || key == nullptr)
			return key;
		std::string s(key);
		auto pos = s.find("##");
		std::string display = (pos == std::string::npos) ? s : s.substr(0, pos);
		auto it = g_table.find(display);
		if (it == g_table.end())
			return key;
		if (pos == std::string::npos)
		{
			g_result = it->second;
		}
		else
		{
			g_result = it->second + s.substr(pos);
		}
		return g_result.c_str();
	}

